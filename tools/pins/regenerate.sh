#!/bin/bash
# Rebuild every committed reference of DiffractoKit from the pinned Python environments, in place, then judge the result
# with tools/pins/compare.py. The Linux reference job (.github/workflows/references.yml) runs exactly this; it also runs
# on a Mac. Run from the repo root.
#
#   tools/pins/regenerate.sh --setup   first build the three venvs, the two pinned source clones, the scattering table
#                                      and the beta'' CIF under ../References and References/ (CONTRIBUTING.md)
#   tools/pins/regenerate.sh           regenerate and compare
#
# A generator listed in tools/pins/known-differences.txt may fail without failing the run; every other failure does.
set -uo pipefail
KIT=$(pwd)
REFS=${REFS:-$KIT/../References}
PY=$REFS/python
PY4DSTEM_LOCK=f050d207851f8accd3aa550365baaf1f38230428
PYMATGEN_CORE_PIN=ae9a8348177b92fe33b214e54e61a3b8f4244b6e

clone() {  # url, commit, destination: a pinned source clone some generators check the installed files against
  [ -d "$3/.git" ] || git clone -q --filter=blob:none "$1" "$3"
  git -C "$3" checkout -q "$2"
}

if [ "${1:-}" = "--setup" ]; then
  set -e
  for oracle in pymatgen orix py4dstem; do
    [ -x "$PY/$oracle/bin/python" ] || python3.12 -m venv "$PY/$oracle"
    "$PY/$oracle/bin/pip" install -q -r "tools/pins/requirements/$oracle.txt"
  done
  clone https://github.com/py4dstem/py4DSTEM "$PY4DSTEM_LOCK" "$REFS/CuboKit/py4DSTEM-f050d207"
  clone https://github.com/materialsproject/pymatgen-core "$PYMATGEN_CORE_PIN" "$REFS/DiffractoKit/pymatgen-core-ae9a834"
  bash tools/pins/structure-factors/fetch-table.sh
  "$PY/pymatgen/bin/python" -I -B tools/crystal-structures/make_beta_double_prime.py
  exit 0
fi

# In order: structure-factors before ring-indexing and phase-vectors (they read its fixture), ring-pins before q-pins,
# cells before conventional-cell (it imports cells), misorientation before orientation-api (it imports it).
generators=(
  pymatgen:structure-factors/pins.py
  pymatgen:ring-calibration/ring-pins.py
  pymatgen:ring-calibration/q-pins.py
  pymatgen:cells/pins.py
  pymatgen:cells/tetragonal-pins.py
  pymatgen:conventional-cell/pins.py
  pymatgen:cif-symmetry/pins.py
  pymatgen:cif-symmetry/hall-pins.py
  pymatgen:presets/pins.py
  pymatgen:mp-import/pins.py
  pymatgen:mp-optimade/pins.py
  pymatgen:ring-indexing/pins.py
  pymatgen:ring-display/ring-overlay-pins.py
  pymatgen:ring-display/indexing-display-pins.py
  pymatgen:ellipse/sweep.py
  pymatgen:orientation-symmetry/trigonal-pins.py
  pymatgen:orientation-symmetry/color-table.py
  pymatgen:phase-vectors/pins.py
  pymatgen:lattice-edit/pins.py
  orix:orix/ipf-pins.py
  orix:orix/direction-pins.py
  orix:orix/disorientation-pins.py
  orix:orix/misorientation-pins.py
  orix:orix/orientation-api-pins.py
  py4dstem:orientation-symmetry/family-pins.py
  py4dstem:orientation-symmetry/family-real-pins.py
  py4dstem:beam-centre/friedel-pins.py
)
# Not run here, each with its reason (they stay Mac-only and are regenerated by hand):
#   orientation-symmetry/pins.py  compiles the app's Swift source (import simd) taken with `git show` from the 4DSTEM Studio
#                                 history; color-table.py above rebuilds its Swift table from the committed fixture
#   acom-matcher/pins.py          records the 4DSTEM Studio working tree's HEAD and file hashes, which move with the app

known=$(sed -e 's/#.*//' -e 's/[[:space:]]*$//' tools/pins/known-differences.txt 2>/dev/null | grep -v '^$' || true)
failed=0
for entry in "${generators[@]}"; do
  oracle=${entry%%:*}; script=${entry#*:}
  echo "::group::$script ($oracle)"
  start=$SECONDS
  "$PY/$oracle/bin/python" -I -B "tools/pins/$script"
  rc=$?
  echo "::endgroup::"
  if [ $rc -ne 0 ]; then
    if grep -qxF "tools/pins/$script" <<<"$known"; then
      echo "::warning::tools/pins/$script exited $rc (listed in tools/pins/known-differences.txt)"
    else
      echo "::error::tools/pins/$script exited $rc"; failed=1
    fi
  fi
  echo "$script: exit $rc, $((SECONDS - start)) s"
done

"$PY/pymatgen/bin/python" -I -B tools/pins/compare.py || failed=1
exit $failed
