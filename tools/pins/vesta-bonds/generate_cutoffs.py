"""Writes Sources/DiffractoCore/VestaBondCutoffs.swift from pymatgen's own VESTA cut-off table.
Run with References/python/pymatgen/bin/python -I -B (tools/pins/requirements/pymatgen.txt).
The table is the one CutOffDictNN.from_preset("vesta_2019") builds from pymatgen/core/vesta_cutoffs.yaml: its
lookup is symmetric and the last entry of a pair wins (the file gives H-O and D-O twice, 2.1 then 1.2; 1.2 wins).
The kit's sites hold an atomic number only, so the deuterium rows (the kit reads D as H) and the "NH" row are left
out; every other row is a pair of elements. No number here is typed.
"""
from pathlib import Path
from importlib.metadata import version
import hashlib, inspect
from pymatgen.analysis.local_env import CutOffDictNN
from pymatgen.core.periodic_table import Element
import pymatgen.core.local_env as local_env
assert version('pymatgen') == '2026.9.24'
assert version('pymatgen-core') == '2026.10.16'

yaml_path = Path(inspect.getfile(local_env)).parent / 'vesta_cutoffs.yaml'
digest = hashlib.sha256(yaml_path.read_bytes()).hexdigest()
nn = CutOffDictNN.from_preset('vesta_2019')
pairs = {}
skipped = set()
for first, row in nn._lookup_dict.items():
    for second, cutoff in row.items():
        if first in ('D', 'NH') or second in ('D', 'NH'):
            skipped.add(tuple(sorted((first, second))))
            continue
        z1, z2 = sorted((Element(first).Z, Element(second).Z))
        assert pairs.get((z1, z2), cutoff) == cutoff, (first, second)
        pairs[(z1, z2)] = cutoff
assert max(pairs.values()) <= nn._max_dist

lines = []
entries = sorted(pairs.items())
for start in range(0, len(entries), 6):
    lines.append('        ' + ' '.join(f'({z1}, {z2}, {cutoff!r}),' for (z1, z2), cutoff in entries[start:start + 6]))
source = f'''//
//  VestaBondCutoffs.swift
//  Role: VESTA's bond cut-offs (Å) per element pair, as pymatgen {version('pymatgen-core')} holds them
//        (CutOffDictNN.from_preset("vesta_2019"), pymatgen/core/vesta_cutoffs.yaml, sha256 {digest}).
//        Generated by tools/pins/vesta-bonds/generate_cutoffs.py; do not edit. {len(entries)} element pairs; the
//        file's {len(skipped)} pairs with deuterium or "NH" are left out (a site here is an atomic number).
//

enum VestaBondCutoffs {{
    /// The pinned file's sha256.
    static let sourceSHA256 = "{digest}"

    /// (smaller atomic number, larger atomic number, cut-off in Å), sorted.
    static let pairs: [(Int, Int, Double)] = [
{chr(10).join(lines)}
    ]
}}
'''
out = Path(__file__).resolve().parents[3] / 'Sources/DiffractoCore/VestaBondCutoffs.swift'
out.write_text(source)
print(f'{len(entries)} pairs written, {len(skipped)} skipped: {sorted(skipped)}')
